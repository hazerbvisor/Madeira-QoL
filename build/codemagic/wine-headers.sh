#!/bin/bash
# Host configuration supplies Wine's generated headers to the hand-built iOS
# unix archives. No host Wine archive is linked into the app.
set -euo pipefail
R="$(cd "$(dirname "$0")/../.." && pwd)"
B="$R/wine/build-macos"
export PATH="$R/toolchains/llvm-mingw-20260421-ucrt-macos-universal/bin:$PATH"
mkdir -p "$B"
cd "$B"
# These host libraries are unnecessary for WIDL. FreeType is built for iOS
# separately; ios_gnutls_shim.h enables the statically linked crypto paths.
../configure --without-x --without-freetype --without-gnutls --disable-tests --enable-winegstreamer
# Configure alone does not generate WIDL headers. Resolve only the include
# closure used by the native translation units, then build host WIDL and those
# headers. No Wine PE/unix library is built here.
python3 "$R/build/codemagic/wine-header-targets.py" > "$B/madeira-header-targets"
HEADERS=()
while IFS= read -r header; do HEADERS+=("$header"); done < "$B/madeira-header-targets"
[ "${#HEADERS[@]}" -gt 0 ] || { echo 'No Wine generated-header targets found' >&2; exit 1; }
make -j "${BUILD_JOBS:-$(sysctl -n hw.ncpu)}" "${HEADERS[@]}"
for header in "${HEADERS[@]}"; do
    [ -s "$header" ] || { echo "Missing generated Wine header: $B/$header" >&2; exit 1; }
done
# config.h is generated by configure; the protocol headers are tracked.
for header in include/config.h ../include/ntstatus.h ../include/wine/server_protocol.h; do
    [ -s "$header" ] || { echo "Missing Wine header: $B/$header" >&2; exit 1; }
done
